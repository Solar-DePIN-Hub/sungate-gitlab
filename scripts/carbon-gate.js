'use strict';
// CI carbon gate. Runs first in every pipeline and writes:
//   carbon-report.json  (artifact, read by Duo flows and the SCI report)
//   carbon.env          (dotenv: CARBON_DECISION, CARBON_I_NOW, ...)
//   heavy.yml           (dynamic child pipeline: real heavy jobs, or a single "deferred" job)
// Policy (CARBON_GATE_MODE):
//   advise  - never delays work; reports the cleaner window (default for push / MR pipelines)
//   enforce - defers heavy jobs when waiting is worth it (default for scheduled batch pipelines)
// A commit title containing [urgent] always runs now.
const fs = require('node:fs');
const path = require('node:path');
const carbon = require('../src/carbon');

const env = process.env;
const mode = env.CARBON_GATE_MODE || (env.CI_PIPELINE_SOURCE === 'schedule' ? 'enforce' : 'advise');
const minSavingPct = Number(env.CARBON_MIN_SAVING_PCT || 30);
const maxWaitH = Number(env.CARBON_MAX_WAIT_H || 6);
const durationMin = Number(env.HEAVY_JOB_MINUTES || 30);
const fallbackI = Number(env.CARBON_FALLBACK_G_PER_KWH || 200);
const urgent = /\[urgent\]/i.test(env.CI_COMMIT_TITLE || '');

// Deferred = the SAME heavy jobs, but behind a GitLab "delayed" job that starts at the green window.
// Delayed jobs hold no runner while waiting, so the wait itself costs no energy.
function heavyPipeline(deferred, report) {
  const heavy = fs.readFileSync(path.join(__dirname, '..', 'ci', 'heavy.yml'), 'utf8');
  if (!deferred) return heavy;
  const reason = report.gate.reason.replace(/"/g, "'");
  return heavy.replace(/^stages:\s*\[/m, 'stages: [green-wait, ') + `
# generated by scripts/carbon-gate.js (enforce mode)
green-window-wait:
  stage: green-wait
  image: node:24-alpine
  when: delayed
  start_in: ${Math.max(1, report.window.waitMin)} minutes
  script:
    - echo "Heavy jobs time-shifted - ${reason}"
    - echo "Green window starts ${report.window.best.start} (${report.window.best.avgGPerKWh} gCO2e/kWh)"
`;
}

function safeWindow(slots, opts) {
  try { return carbon.greenWindow(slots, opts); } catch { return null; }
}

(async () => {
  let slots = null, error = null;
  try { slots = await carbon.fetchForecast(); } catch (e) { error = e.message; }
  const report = { spec: 'GSF SCI v1.0 (ISO/IEC 21031:2024)', mode, generatedAt: new Date().toISOString(), source: 'carbonintensity.org.uk (GB)', urgent };
  const w = slots && slots.length ? safeWindow(slots, { durationMin, horizonH: maxWaitH }) : null;
  if (w) {
    report.window = w;
    report.window24h = safeWindow(slots, { durationMin, horizonH: 24 }) || w;
    report.gate = carbon.decide(report.window, { minSavingPct, maxWaitH });
  } else {
    report.window = { now: { start: report.generatedAt, avgGPerKWh: fallbackI }, best: { start: report.generatedAt, avgGPerKWh: fallbackI }, waitMin: 0, savingPct: 0 };
    report.window24h = report.window;
    report.gate = { decision: 'run', reason: `carbon data unavailable (${error || 'not enough forecast slots'}); using fallback ${fallbackI} gCO2e/kWh and running` };
  }
  const deferred = mode === 'enforce' && report.gate.decision === 'defer' && !urgent;
  report.effective = deferred ? 'deferred' : 'run';
  fs.writeFileSync('carbon-report.json', JSON.stringify(report, null, 2));
  fs.writeFileSync('carbon.env', [
    `CARBON_DECISION=${report.effective}`,
    `CARBON_I_NOW=${report.window.now.avgGPerKWh}`,
    `CARBON_BEST_START=${report.window24h.best.start}`,
    `CARBON_BEST_I=${report.window24h.best.avgGPerKWh}`,
    `CARBON_SAVING_PCT=${report.window24h.savingPct}`,
  ].join('\n') + '\n');
  fs.writeFileSync('heavy.yml', heavyPipeline(deferred, report));
  console.log(`carbon gate [${mode}] -> ${report.effective}: ${report.gate.reason}`);
  console.log(`now ${report.window.now.avgGPerKWh} gCO2e/kWh; greenest in 24h ${report.window24h.best.avgGPerKWh} at ${report.window24h.best.start}`);
})().catch(e => { console.error(e); process.exit(1); });
